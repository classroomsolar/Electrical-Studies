"""Batch 2 browser checks: BESS dispatch / sizing hidden (D-04), time-series load flow still works,
Sitka font stack applied (D-09), Cloud Vault file input labelled (I-04). Usage: python3 b02_browser.py SITE_DIR PORT"""
import sys,subprocess,time,json,os
from playwright.sync_api import sync_playwright
site,port=sys.argv[1],int(sys.argv[2]);out=os.path.join(os.path.dirname(os.path.abspath(__file__)),'results')
srv=subprocess.Popen([sys.executable,'-m','http.server',str(port),'-d',site],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL);time.sleep(1)
R=[];ok=lambda n,c,i='':(R.append({'check':n,'pass':bool(c),'info':str(i)[:300]}),print(('PASS ' if c else 'FAIL ')+n,str(i)[:160]))
with sync_playwright() as p:
  b=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox','--disable-dev-shm-usage'])
  pg=b.new_page(viewport={'width':1440,'height':900});errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
  pg.goto(f'http://127.0.0.1:{port}/index.html');pg.wait_for_timeout(4000)
  f=pg.evaluate("()=>({body:getComputedStyle(document.body).fontFamily,h:(()=>{const h=document.querySelector('h1,h2,h3');return h?getComputedStyle(h).fontFamily:''})(),code:(()=>{const c=document.createElement('code');document.body.append(c);const v=getComputedStyle(c).fontFamily;c.remove();return v})()})")
  ok('body text uses the Sitka Text stack',f['body'].startswith('"Sitka Text"'),f['body'])
  ok('headings use the Sitka Heading stack',f['h'].startswith('"Sitka Heading"'),f['h'])
  ok('code stays monospace',('monospace' in f['code']) and 'Sitka' not in f['code'],f['code'])
  fonts=pg.evaluate("()=>performance.getEntriesByType('resource').map(e=>e.name).filter(n=>/\\.woff2?|fonts\\//.test(n))")
  ok('no font file is requested',not fonts,fonts)
  pg.screenshot(path=os.path.join(out,'main_1440.png'))
  # Operations lab
  opened=pg.evaluate("()=>{const b=document.querySelector('[data-v27-launch]');if(!b)return 'no launcher';b.click();return b.textContent}")
  pg.wait_for_timeout(800)
  ok('launcher no longer says BESS','BESS' not in opened and opened!='no launcher',opened)
  st=pg.evaluate("()=>{const o=document.getElementById('v27-operations');const q=s=>o.querySelector(s);return {visible:o&&!o.hidden,heading:q('#v27-heading')?.textContent,bessHidden:q('[data-v27-mode=bess]')?.hidden,sweepHidden:q('[data-v27-mode=sweep]')?.hidden,acPressed:q('[data-v27-mode=ac]')?.getAttribute('aria-pressed'),note:q('[data-out-of-scope-note]')?.textContent||'',bessFields:!!q('[data-v27-field=capacityKWh]'),sweepFields:!!q('[data-v27-field=capacityCandidatesKWh]')}}")
  ok('lab opens',st['visible'],st)
  ok('BESS dispatch and sizing tabs hidden',st['bessHidden'] and st['sweepHidden'],st)
  ok('time-series load flow is the active mode',st['acPressed']=='true' and not st['bessFields'] and not st['sweepFields'],st)
  ok('scope note shown','not in the scope' in st['note'],st['note'])
  ok('heading no longer says BESS','BESS' not in (st['heading'] or ''),st['heading'])
  pg.evaluate("()=>document.querySelector('#v27-operations [type=submit]').click()")
  pg.wait_for_timeout(1500)
  res=pg.evaluate("()=>{const o=document.getElementById('v27-operations');return (o.querySelector('#v27-output')?.textContent||'').slice(0,200)}")
  err=pg.evaluate("()=>(document.querySelector('#v27-operations .v27-error,#v27-operations [role=alert]')?.textContent||'')")
  ok('time-series load flow example calculates',res.strip()!='' and not err,res or err)
  # importing a BESS scenario is refused with the scope message
  pg.evaluate("""()=>{const i=document.getElementById('v27-import');const f=new File([JSON.stringify({format:'fcs-operations-v27',mode:'bess',input:{a:1}})],'b.json',{type:'application/json'});const d=new DataTransfer();d.items.add(f);i.files=d.files;i.dispatchEvent(new Event('change',{bubbles:true}))}""")
  pg.wait_for_timeout(800)
  msg=pg.evaluate("()=>document.getElementById('v27-operations').innerText")
  ok('imported BESS scenario is refused with the scope message','BESS dispatch or sizing study' in msg,'')
  pg.screenshot(path=os.path.join(out,'operations_lab_1440.png'))
  pg.evaluate("()=>document.querySelector('#v27-operations [data-v27=close]')?.click()")
  # Cloud Vault label
  pg.evaluate("()=>{const b=[...document.querySelectorAll('button')].find(b=>/Cloud Vault/.test(b.textContent));b&&b.click()}");pg.wait_for_timeout(1000)
  lab=pg.evaluate("()=>{const i=document.getElementById('fcs-original-backup');return i?(i.labels?.[0]?.textContent||''):'no input'}")
  ok('Cloud Vault backup input has a label',lab not in ('','no input'),lab)
  ok('no page errors',not errs,errs)
  b.close()
srv.terminate()
json.dump(R,open(os.path.join(out,'b02_browser.json'),'w'),indent=1)
print({'pass':sum(r['pass'] for r in R),'fail':sum(not r['pass'] for r in R)})
